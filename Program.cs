// DISCOVER
app.MapGet("/users/discover/{userId:int}", async (
    int userId,
    AppDbContext db) =>
{
    if (userId <= 0)
    {
        return Results.BadRequest(new
        {
            message = "Geçersiz kullanıcı"
        });
    }

    // Giriş yapan kullanıcıyı bul
    var currentUser = await db.Users
        .AsNoTracking()
        .FirstOrDefaultAsync(x => x.Id == userId);

    if (currentUser == null)
    {
        return Results.NotFound(new
        {
            message = "Kullanıcı bulunamadı"
        });
    }

    var blockedIds = await db.UserBlocks.AsNoTracking()
        .Where(x => x.BlockerUserId == userId || x.BlockedUserId == userId)
        .Select(x => x.BlockerUserId == userId ? x.BlockedUserId : x.BlockerUserId)
        .Distinct().ToListAsync();

    // Daha önce swipe edilen kullanıcıları bul
    var swipedIds = await db.Swipes
        .AsNoTracking()
        .Where(x => x.FromUserId == userId)
        .Select(x => x.ToUserId)
        .Distinct()
        .ToListAsync();

    string myGender = (currentUser.Gender ?? "")
        .Trim()
        .ToLower();

    // Erkek -> kadın
    // Kadın -> erkek
    bool currentUserIsMale =
        myGender == "erkek" ||
        myGender == "male";

    bool currentUserIsFemale =
        myGender == "kadın" ||
        myGender == "kadin" ||
        myGender == "female";

    var candidates = await db.Users
        .AsNoTracking()
        .Where(x =>
            x.Id != userId &&
            !swipedIds.Contains(x.Id) &&
            !blockedIds.Contains(x.Id))
        .OrderByDescending(x => x.CreatedAtUtc)
        .ToListAsync();

    // Cinsiyet filtresi
    if (currentUserIsMale)
    {
        candidates = candidates
            .Where(x =>
            {
                string gender = (x.Gender ?? "")
                    .Trim()
                    .ToLower();

                return gender == "kadın" ||
                       gender == "kadin" ||
                       gender == "female";
            })
            .ToList();
    }
    else if (currentUserIsFemale)
    {
        candidates = candidates
            .Where(x =>
            {
                string gender = (x.Gender ?? "")
                    .Trim()
                    .ToLower();

                return gender == "erkek" ||
                       gender == "male";
            })
            .ToList();
    }

    var users = candidates
        .Select(ToDto)
        .ToList();

    return Results.Ok(users);
});

// SWIPE
app.MapPost("/swipes", async (
    SwipeRequest req,
    AppDbContext db) =>
{
    if (req.FromUserId <= 0 || req.ToUserId <= 0)
        return Results.BadRequest(new { message = "Geçersiz kullanıcı" });

    if (req.FromUserId == req.ToUserId)
        return Results.BadRequest(new { message = "Kendini beğenemezsin" });

    if (await db.UserBlocks.AnyAsync(x =>
        (x.BlockerUserId == req.FromUserId && x.BlockedUserId == req.ToUserId) ||
        (x.BlockerUserId == req.ToUserId && x.BlockedUserId == req.FromUserId)))
        return Results.BadRequest(new { message = "Engellenen kullanıcıyla etkileşim kurulamaz" });

    var old = await db.Swipes.FirstOrDefaultAsync(x =>
        x.FromUserId == req.FromUserId &&
        x.ToUserId == req.ToUserId);

    if (old == null)
    {
        db.Swipes.Add(new Swipe
        {
            FromUserId = req.FromUserId,
            ToUserId = req.ToUserId,
            IsLike = req.IsLike,
            CreatedAtUtc = DateTime.UtcNow
        });
    }
    else
    {
        old.IsLike = req.IsLike;
        old.CreatedAtUtc = DateTime.UtcNow;
    }

    await db.SaveChangesAsync();

    if (!req.IsLike)
        return Results.Ok(new SwipeResponse { Matched = false });

    var mutual = await db.Swipes.AnyAsync(x =>
        x.FromUserId == req.ToUserId &&
        x.ToUserId == req.FromUserId &&
        x.IsLike);

    if (!mutual)
        return Results.Ok(new SwipeResponse { Matched = false });

    var u1 = Math.Min(req.FromUserId, req.ToUserId);
    var u2 = Math.Max(req.FromUserId, req.ToUserId);

    var matchExists = await db.Matches.AnyAsync(x =>
        x.User1Id == u1 &&
        x.User2Id == u2);

    if (!matchExists)
    {
        db.Matches.Add(new Match
        {
            User1Id = u1,
            User2Id = u2,
            CreatedAtUtc = DateTime.UtcNow
        });

        await db.SaveChangesAsync();
    }

    return Results.Ok(new SwipeResponse { Matched = true });
});

