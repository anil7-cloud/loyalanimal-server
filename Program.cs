app.MapPost("/messages", async (
    SendMessageRequest req,
    AppDbContext db) =>
{
    if (string.IsNullOrWhiteSpace(req.Text))
        return Results.BadRequest(new { message = "Mesaj boş" });

    if (await db.UserBlocks.AnyAsync(x =>
        (x.BlockerUserId == req.SenderUserId && x.BlockedUserId == req.ReceiverUserId) ||
        (x.BlockerUserId == req.ReceiverUserId && x.BlockedUserId == req.SenderUserId)))
        return Results.BadRequest(new { message = "Engellenen kullanıcıyla mesajlaşılamaz" });

    var a = Math.Min(req.SenderUserId, req.ReceiverUserId);
    var b = Math.Max(req.SenderUserId, req.ReceiverUserId);

    var matched = await db.Matches.AnyAsync(x =>
        x.User1Id == a &&
        x.User2Id == b);

    if (!matched)
        return Results.BadRequest(new { message = "Match yok" });

    var msg = new Message
    {
        SenderUserId = req.SenderUserId,
        ReceiverUserId = req.ReceiverUserId,
        Text = req.Text.Trim(),
        CreatedAtUtc = DateTime.UtcNow
    };

    db.Messages.Add(msg);
    await db.SaveChangesAsync();

    return Results.Ok(new MessageDto
    {
        Id = msg.Id,
        SenderUserId = msg.SenderUserId,
        ReceiverUserId = msg.ReceiverUserId,
        Text = msg.Text,
        CreatedAt = msg.CreatedAtUtc
    });
});


