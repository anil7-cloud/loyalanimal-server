app.MapPut("/pets/{id:int}", async (
    int id,
    LoyalAnimal.Shared.Pet input,
    AppDbContext db,
    System.Security.Claims.ClaimsPrincipal principal) =>
{
    var authenticatedUserId =
        LoyalAnimal.Server.Security.AuthenticatedUser.GetUserId(principal);

    if (authenticatedUserId is null)
        return Results.Unauthorized();

    var pet = await db.Pets.FirstOrDefaultAsync(x => x.Id == id);

    if (pet is null)
        return Results.NotFound();

    if (pet.OwnerUserId != authenticatedUserId.Value)
        return Results.Forbid();

    if (string.IsNullOrWhiteSpace(input.Name))
        return Results.BadRequest("Pet adı gerekli.");

    // Hayvanın sahibi güncelleme yoluyla değiştirilemez.
    pet.Name = input.Name;
    pet.Type = input.Type;
    pet.Breed = input.Breed;
    pet.Age = input.Age;
    pet.PhotoUrl = input.PhotoUrl;

    await db.SaveChangesAsync();

    return Results.Ok(pet);
}).RequireAuthorization();

