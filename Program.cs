// UPLOAD USER PHOTO TO CLOUDINARY
app.MapPost("/users/{id:int}/photo/upload", async (
    int id,
    HttpRequest request,
    AppDbContext db,
    System.Security.Claims.ClaimsPrincipal principal) =>
{
    var authenticatedUserId =
        LoyalAnimal.Server.Security.AuthenticatedUser.GetUserId(principal);

    if (authenticatedUserId is null)
        return Results.Unauthorized();

    if (authenticatedUserId.Value != id)
        return Results.Forbid();

    var user = await db.Users.FirstOrDefaultAsync(x => x.Id == id);

    if (user == null)
        return Results.NotFound(new { message = "Kullanıcı bulunamadı" });

    if (!request.HasFormContentType)
        return Results.BadRequest(new { message = "Form-data bekleniyor" });

    var form = await request.ReadFormAsync();
    var file = form.Files.FirstOrDefault();

    if (file == null || file.Length == 0)
        return Results.BadRequest(new { message = "Dosya bulunamadı" });

    const long maxPhotoBytes = 5 * 1024 * 1024;
    if (file.Length > maxPhotoBytes)
        return Results.BadRequest(new { message = "Fotoğraf en fazla 5 MB olabilir." });

    await using var stream = file.OpenReadStream();

    var header = new byte[12];
    var bytesRead = 0;
    while (bytesRead < header.Length)
    {
        var count = await stream.ReadAsync(
            header.AsMemory(bytesRead, header.Length - bytesRead));
        if (count == 0)
            break;
        bytesRead += count;
    }

    var isJpeg = bytesRead >= 3 &&
        header[0] == 0xFF && header[1] == 0xD8 && header[2] == 0xFF;

    var isPng = bytesRead >= 8 &&
        header.AsSpan(0, 8).SequenceEqual(
            new byte[] { 137, 80, 78, 71, 13, 10, 26, 10 });

    var isWebp = bytesRead >= 12 &&
        header.AsSpan(0, 4).SequenceEqual("RIFF"u8) &&
        header.AsSpan(8, 4).SequenceEqual("WEBP"u8);

    if (!isJpeg && !isPng && !isWebp)
        return Results.BadRequest(new
        {
            message = "Yalnızca JPEG, PNG veya WebP fotoğrafları yüklenebilir."
        });

    stream.Position = 0;

    var cloudName = Environment.GetEnvironmentVariable("CLOUDINARY_CLOUD_NAME")?.Trim();
    var apiKey = Environment.GetEnvironmentVariable("CLOUDINARY_API_KEY")?.Trim();
    var apiSecret = Environment.GetEnvironmentVariable("CLOUDINARY_API_SECRET")?.Trim();

    if (string.IsNullOrWhiteSpace(cloudName) ||
        string.IsNullOrWhiteSpace(apiKey) ||
        string.IsNullOrWhiteSpace(apiSecret))
    {
        return Results.BadRequest(new { message = "Cloudinary ayarları eksik" });
    }

    var account = new Account(cloudName, apiKey, apiSecret);
    var cloudinary = new Cloudinary(account);

    var uploadParams = new ImageUploadParams
    {
        File = new FileDescription(file.FileName, stream),
        Folder = "loyalanimal/users",
        PublicId = $"user_{id}_{DateTime.UtcNow.Ticks}",
        Overwrite = true
    };

    var uploadResult = await cloudinary.UploadAsync(uploadParams);

    if (uploadResult.Error != null)
        return Results.BadRequest(new { message = uploadResult.Error.Message });

    user.PhotoUrl = uploadResult.SecureUrl.ToString();
    await db.SaveChangesAsync();

    return Results.Ok(ToDto(user));
}).RequireAuthorization();


