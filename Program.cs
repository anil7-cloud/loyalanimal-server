app.MapGet("/users/discover/{userId:int}", async (
    int userId,
    AppDbContext db,
    System.Security.Claims.ClaimsPrincipal principal) =>
{
    var authenticatedUserId =
        LoyalAnimal.Server.Security.AuthenticatedUser.GetUserId(principal);

    if (authenticatedUserId is null)
        return Results.Unauthorized();

    if (authenticatedUserId.Value != userId)
        return Results.Forbid();

    if (userId <= 0)
    {
        return Results.BadRequest(new
        {
            message = "Geçersiz kullanıcı"
        });
    }

    // Giriş yapan kullanıcıyı bul
    var currentUser = await db.Users
        .AsNoTracking()
        .FirstOrDefaultAsync(x => x.Id == userId);

    if (currentUser == null)
    {
        return Results.NotFound(new
        {
            message = "Kullanıcı bulunamadı"
        });
    }

    var blockedIds = await db.UserBlocks.AsNoTracking()
        .Where(x => x.BlockerUserId == userId || x.BlockedUserId == userId)
        .Select(x => x.BlockerUserId == userId ? x.BlockedUserId : x.BlockerUserId)
        .Distinct().ToListAsync();

    // Daha önce swipe edilen kullanıcıları bul
    var swipedIds = await db.Swipes
        .AsNoTracking()
        .Where(x => x.FromUserId == userId)
        .Select(x => x.ToUserId)
        .Distinct()
        .ToListAsync();

    string myGender = (currentUser.Gender ?? "")
        .Trim()
        .ToLower();

    // Erkek -> kadın
    // Kadın -> erkek
    bool currentUserIsMale =
        myGender == "erkek" ||
        myGender == "male";

    bool currentUserIsFemale =
        myGender == "kadın" ||
        myGender == "kadin" ||
        myGender == "female";

