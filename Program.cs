app.MapPost("/products/{productId:int}/image", async (
    int productId,
    HttpRequest request,
    ClaimsPrincipal principal,
    AppDbContext db) =>
{
    var userId =
        LoyalAnimal.Server.Security.AuthenticatedUser.GetUserId(principal);

    if (userId is null)
        return Results.Unauthorized();

    var product = await db.Products
        .FirstOrDefaultAsync(p => p.Id == productId && p.IsActive);

    if (product is null)
        return Results.NotFound(new { message = "Ürün bulunamadı." });

    var shop = await db.Shops.FirstOrDefaultAsync(s =>
        s.Id == product.ShopId &&
        s.OwnerUserId == userId.Value &&
        s.IsApproved &&
        s.IsActive);

    if (shop is null)
    {
        return Results.Json(
            new { message = "Bu ürüne fotoğraf yükleme yetkiniz yok." },
            statusCode: StatusCodes.Status403Forbidden);
    }

    if (!request.HasFormContentType)
        return Results.BadRequest(new { message = "Fotoğraf gerekli." });

    var form = await request.ReadFormAsync();
    var file = form.Files.GetFile("file");

    if (file is null || file.Length == 0)
        return Results.BadRequest(new { message = "Fotoğraf seçilmedi." });

    // 10 MB sınırı
    if (file.Length > 10 * 1024 * 1024)
        return Results.BadRequest(new { message = "Fotoğraf en fazla 10 MB olabilir." });

    var allowedTypes = new[]
    {
        "image/jpeg",
        "image/png",
        "image/webp"
    };

    if (!allowedTypes.Contains(file.ContentType.ToLowerInvariant()))
    {
        return Results.BadRequest(new
        {
            message = "Yalnızca JPG, PNG veya WEBP yüklenebilir."
        });
    }

    await using var stream = file.OpenReadStream();

    var cloudName =
        Environment.GetEnvironmentVariable("CLOUDINARY_CLOUD_NAME")?.Trim();

    var apiKey =
        Environment.GetEnvironmentVariable("CLOUDINARY_API_KEY")?.Trim();

    var apiSecret =
        Environment.GetEnvironmentVariable("CLOUDINARY_API_SECRET")?.Trim();

    if (string.IsNullOrWhiteSpace(cloudName) ||
        string.IsNullOrWhiteSpace(apiKey) ||
        string.IsNullOrWhiteSpace(apiSecret))
    {
        return Results.BadRequest(new
        {
            message = "Cloudinary ayarları eksik."
        });
    }

    var account = new Account(cloudName, apiKey, apiSecret);
    var cloudinary = new Cloudinary(account);

    var uploadParams = new ImageUploadParams
    {
        File = new FileDescription(file.FileName, stream),
        Folder = "loyalanimal/products",
        PublicId = $"product_{product.Id}_{DateTime.UtcNow.Ticks}",
        Overwrite = true
    };

    var uploadResult = await cloudinary.UploadAsync(uploadParams);

    if (uploadResult.Error != null)
    {
        return Results.BadRequest(new
        {
            message = uploadResult.Error.Message
        });
    }

    product.ImageUrl = uploadResult.SecureUrl.ToString();

    // Görsel değiştiği için ürün yeniden yönetici onayına gider.
    product.IsApproved = false;

    await db.SaveChangesAsync();

    return Results.Ok(new
    {
        message = "Ürün fotoğrafı yüklendi.",
        imageUrl = product.ImageUrl,
        product
    });
}).RequireAuthorization();



