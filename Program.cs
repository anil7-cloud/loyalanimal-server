// EMAIL + PASSWORD REGISTRATION
app.MapPost("/auth/register", async (
    EmailRegisterRequest req,
    AppDbContext db) =>
{
    var email = req.Email?.Trim().ToLowerInvariant() ?? "";
    var password = req.Password ?? "";

    if (email.Length > 254 ||
        password.Length < 12 ||
        password.Length > 128 ||
        string.IsNullOrWhiteSpace(req.DisplayName) ||
        string.IsNullOrWhiteSpace(req.City) ||
        string.IsNullOrWhiteSpace(req.Gender) ||
        req.Age <= 0)
    {
        return Results.BadRequest(new
        {
            message = "Geçerli profil bilgileri ve 12-128 karakterlik parola gerekli."
        });
    }

    try
    {
        var address = new MailAddress(email);

        if (address.Address != email)
            return Results.BadRequest(new
            {
                message = "Geçersiz e-posta adresi."
            });
    }
    catch (FormatException)
    {
        return Results.BadRequest(new
        {
            message = "Geçersiz e-posta adresi."
        });
    }

    if (await db.Users.AnyAsync(u => u.Email.ToLower() == email))
    {
        return Results.Conflict(new
        {
            message = "Bu e-posta adresiyle kayıt yapılamıyor."
        });
    }

    var user = new User
    {
        Email = email,
        Username = req.DisplayName.Trim(),
        City = req.City.Trim(),
        Age = req.Age,
        Gender = req.Gender.Trim(),
        IsEmailVerified = true,
        EmailVerificationTokenHash = null,
        EmailVerificationExpiresAtUtc = null,
        CreatedAtUtc = DateTime.UtcNow
    };

    user.PasswordHash = PasswordService.Hash(user, password);

    db.Users.Add(user);
    await db.SaveChangesAsync();

    return Results.Ok(new
    {
        message = "Kayıt başarılı."
    });
});


// VERIFY EMAIL
app.MapGet("/auth/verify-email", async (
    int userId,
    string token,
    AppDbContext db) =>
{
    if (userId <= 0 ||
        string.IsNullOrWhiteSpace(token) ||
        token.Length != 64)
    {
        return Results.BadRequest("Geçersiz doğrulama bağlantısı.");
    }

    var user = await db.Users.FirstOrDefaultAsync(u => u.Id == userId);

    if (user is null)
        return Results.BadRequest("Geçersiz doğrulama bağlantısı.");

    if (user.IsEmailVerified)
        return Results.BadRequest("Bu bağlantı artık geçerli değil.");

    var valid = EmailVerificationTokenService.VerifyToken(
        token,
        user.EmailVerificationTokenHash,
        user.EmailVerificationExpiresAtUtc);

    if (!valid)
        return Results.BadRequest(
            "Doğrulama bağlantısı geçersiz veya süresi dolmuş.");

    user.IsEmailVerified = true;
    user.EmailVerificationTokenHash = null;
    user.EmailVerificationExpiresAtUtc = null;

    await db.SaveChangesAsync();

    return Results.Content(
        """
        <!doctype html>
        <html lang="tr">
        <head>
            <meta charset="utf-8">
            <meta name="viewport" content="width=device-width, initial-scale=1">
            <title>LoyalAnimal - E-posta doğrulandı</title>
        </head>
        <body style="font-family:Arial,sans-serif;text-align:center;padding:48px">
            <h1>E-posta adresin doğrulandı!</h1>
            <p>LoyalAnimal uygulamasına dönerek giriş yapabilirsin.</p>
        </body>
        </html>
        """,
        "text/html; charset=utf-8");
});



// RESEND EMAIL VERIFICATION
app.MapPost("/auth/resend-verification", async (
    EmailLoginRequest req,
    AppDbContext db,
    VerificationEmailService emailService) =>
{
    var email = req.Email?.Trim().ToLowerInvariant() ?? "";
    var password = req.Password ?? "";

    if (string.IsNullOrWhiteSpace(email) ||
        string.IsNullOrWhiteSpace(password))
    {
        return Results.BadRequest(new
        {
            message = "E-posta adresi ve parola gerekli."
        });
    }

    var user = await db.Users.FirstOrDefaultAsync(
        u => u.Email.ToLower() == email);

    if (user is null ||
        string.IsNullOrWhiteSpace(user.PasswordHash) ||
        !PasswordService.Verify(user, password))
    {
        return Results.Json(
            new { message = "E-posta adresi veya parola hatalı." },
            statusCode: StatusCodes.Status401Unauthorized);
    }

    if (user.IsEmailVerified)
    {
        return Results.BadRequest(new
        {
            message = "E-posta adresi zaten doğrulanmış."
        });
    }

    // Eski hesapları yalnızca profil bilgileriyle sahiplenmeye izin verme.
    if (string.IsNullOrWhiteSpace(user.EmailVerificationTokenHash))
    {
        return Results.BadRequest(new
        {
            message = "Bu hesap için doğrulama bağlantısı oluşturulamıyor."
        });
    }

    var now = DateTime.UtcNow;
    if (user.EmailVerificationLastSentAtUtc is DateTime lastSent &&
        now - lastSent < TimeSpan.FromMinutes(5))
    {
        return Results.Json(
            new { message = "Yeni e-posta istemeden önce 5 dakika bekleyin." },
            statusCode: StatusCodes.Status429TooManyRequests);
    }

    var baseUrl = Environment.GetEnvironmentVariable("PUBLIC_API_BASE_URL");
    if (string.IsNullOrWhiteSpace(baseUrl) ||
        !Uri.TryCreate(baseUrl, UriKind.Absolute, out var uri) ||
        (uri.Scheme != Uri.UriSchemeHttps &&
         !(builder.Environment.IsDevelopment() &&
           uri.Scheme == Uri.UriSchemeHttp &&
           uri.IsLoopback)))
    {
        return Results.Problem(
            "Sunucunun doğrulama bağlantısı ayarı eksik.",
            statusCode: 503);
    }

    var token = EmailVerificationTokenService.GenerateToken();
    var verificationUrl =
        baseUrl.TrimEnd('/') +
        "/auth/verify-email?userId=" + user.Id +
        "&token=" + Uri.EscapeDataString(token);

    var previousTokenHash = user.EmailVerificationTokenHash;
    var previousExpiry = user.EmailVerificationExpiresAtUtc;
    var previousLastSent = user.EmailVerificationLastSentAtUtc;

    var newTokenHash = EmailVerificationTokenService.HashToken(token);
    var newExpiry = EmailVerificationTokenService.GetExpirationUtc();
    var reservedAt = DateTime.UtcNow;
    var cutoff = reservedAt.AddMinutes(-5);

    var updated = await db.Users
        .Where(u => u.Id == user.Id &&
                    !u.IsEmailVerified &&
                    u.EmailVerificationTokenHash == previousTokenHash &&
                    (u.EmailVerificationLastSentAtUtc == null ||
                     u.EmailVerificationLastSentAtUtc <= cutoff))
        .ExecuteUpdateAsync(setters => setters
            .SetProperty(u => u.EmailVerificationTokenHash, newTokenHash)
            .SetProperty(u => u.EmailVerificationExpiresAtUtc, newExpiry)
            .SetProperty(u => u.EmailVerificationLastSentAtUtc, reservedAt));

    if (updated != 1)
    {
        return Results.Json(
            new { message = "Yeni e-posta istemeden önce 5 dakika bekleyin." },
            statusCode: StatusCodes.Status429TooManyRequests);
    }

    try
    {
        await emailService.SendAsync(email, verificationUrl);
    }
    catch (Exception)
    {
        await db.Users
            .Where(u => u.Id == user.Id &&
                        !u.IsEmailVerified &&
                        u.EmailVerificationTokenHash == newTokenHash &&
                        u.EmailVerificationLastSentAtUtc == reservedAt)
            .ExecuteUpdateAsync(setters => setters
                .SetProperty(u => u.EmailVerificationTokenHash, previousTokenHash)
                .SetProperty(u => u.EmailVerificationExpiresAtUtc, previousExpiry)
                .SetProperty(u => u.EmailVerificationLastSentAtUtc, previousLastSent));

        return Results.Problem(
            "Doğrulama e-postası gönderilemedi. Daha sonra yeniden deneyin.",
            statusCode: 503);
    }

    return Results.Accepted(value: new
    {
        message = "Yeni doğrulama bağlantısı e-posta adresine gönderildi."
    });
});

